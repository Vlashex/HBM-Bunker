"""Generate the isolated full-fork HBM progression scripts and strict raw-only EMC configuration."""
import argparse
import json
import re
from pathlib import Path
try:
    from tools import legacy_materials, legacy_sieve_pricing
except ModuleNotFoundError:
    import legacy_materials, legacy_sieve_pricing

ROOT = Path(__file__).resolve().parents[1]
ITEM = re.compile(r'[a-z0-9_]+:[a-z0-9_./]+(?::[0-9]+)?\Z')
MAPPERS = ('OreDictionaryMapper', 'APICustomEMCMapper', 'CustomConversionMapper', 'CustomEMCMapper', 'CraftingMapper', 'FluidMapper', 'SmeltingMapper', 'APICustomConversionMapper')


def load(root, name):
    data = json.loads((root / 'legacy/progression' / name).read_text(encoding='utf-8'))
    if data.get('schema') != 1:
        raise ValueError('Unsupported progression schema: ' + name)
    return data


def ingredient(value):
    if isinstance(value, dict):
        return '<minecraft:enchanted_book>.onlyWithTag(' + tag(value['enchantment'], value['level']) + ')'
    if value.startswith('ore:'):
        if not re.fullmatch(r'ore:[A-Za-z][A-Za-z0-9]*', value):
            raise ValueError('Unsafe ore ingredient')
    elif not ITEM.fullmatch(value):
        raise ValueError('Unsafe item ingredient: ' + value)
    return '<' + value + '>'


def tag(enchantment, level):
    if enchantment not in (32, 33, 34, 35) or not 1 <= level <= 10:
        raise ValueError('Unexpected high enchantment')
    return '{StoredEnchantments: [{id: %s as short, lvl: %s as short}]}' % (enchantment, level)


def compressed_raw_values(root, raw):
    """Only physical compression of an already-priced raw material can gain EMC."""
    document = json.loads((root / 'legacy/sieving/materials.json').read_text(encoding='utf-8'))
    if document.get('schema') != 1 or not 4 <= len(document['materials']) <= 32:
        raise ValueError('Compressed material schema/bounds')
    values, seen = {}, set()
    for row in document['materials']:
        name = row['material']
        if not re.fullmatch('[a-z_]+', name) or name in seen:
            raise ValueError('Unsafe/duplicate compressed material')
        seen.add(name)
        base = raw.get(row['raw_id'] + '|' + str(row['raw_meta']))
        level1 = row.get('native_level1_id') or row.get('own_level1_id')
        level1_meta = row['native_level1_meta'] if row.get('native_level1_id') else row.get('own_level1_meta', 0)
        if not ITEM.fullmatch(level1): raise ValueError('Invalid first compression item')
        if base is not None: values[level1 + '|' + str(level1_meta)] = base * 9
        for level in row['levels']:
            power = level['compression_power']
            if (power not in (1, 2, 3, 4) or level['raw_equivalents'] != 9 ** power
                    or level['id'] != 'dead_earth:compressed_' + name + '_' + str(power)
                    or level['meta'] != 0):
                raise ValueError('Unsafe compressed raw derivation')
            if base is not None: values[level['id'] + '|0'] = base * 9 ** power
    return values


def sieve_input_keys(root):
    """Block sieve feedstock, retaining the explicitly approved dirt/leaves exceptions."""
    materials = json.loads((root / 'legacy/sieving/materials.json').read_text(encoding='utf-8'))
    exceptions = load(root, 'emc.json').get('sieveInputEmcExceptions', [])
    names = {r['material'] for r in materials['materials']}
    if not isinstance(exceptions, list) or len(set(exceptions)) != len(exceptions) or not set(exceptions) <= names:
        raise ValueError('Invalid sieve EMC exceptions')
    raw = {r['raw_id'] + '|' + str(r['raw_meta']): 1
           for r in materials['materials'] if r['currently_siftable']}
    raw.update({legacy_sieve_pricing.key(row['input']): 1 for row in load(root, 'sieve.json')['drops']})
    raw.pop('minecraft:cobblestone|0', None)
    for row in materials['materials']:
        if row['material'] in exceptions:
            raw.pop(row['raw_id'] + '|' + str(row['raw_meta']), None)
    return set(raw) | set(compressed_raw_values(root, raw))


def products(root=ROOT):
    data, sieve, emc = load(root, 'recipes.json'), load(root, 'sieve.json'), load(root, 'emc.json')
    lines = ['// Generated by tools/legacy_full_recipes.py from legacy/progression/*.json.',
             '// Early SimpleStorageNetwork recipes remain in their unchanged two-iron-plate source.',
             '// HBM analog/basic/advanced circuit metadata = 7/8/9, AE2 native material metadata retained.', '']
    for pattern in data['removeRecipeRegex']:
        if pattern != '(?i)mysticalagriculture:.*steel.*':
            raise ValueError('Unexpected recipe removal')
        lines += ['// Keep steel metallurgy in HBM; raw material plant recipes remain available.',
                  'recipes.removeByRegex("' + pattern + '");', '']
    seen, required = set(), {'minecraft:enchanted_book'}
    for recipe in data['recipes'] + data['books']:
        name = recipe['name']
        if not re.fullmatch('[a-z0-9_]+', name) or name in seen:
            raise ValueError('Unsafe/duplicate progression recipe')
        seen.add(name)
        pattern, key = recipe['pattern'], recipe['key']
        if len(pattern) != 3 or any(len(row) != 3 for row in pattern) or set(''.join(pattern)) - {' '} != set(key):
            raise ValueError('Invalid shaped progression recipe')
        grid = ['[' + ', '.join('null' if c == ' ' else ingredient(key[c]) for c in row) + ']' for row in pattern]
        for value in key.values():
            if isinstance(value, str) and not value.startswith('ore:'):
                required.add(value)
        if 'enchantment' in recipe:
            result = '<minecraft:enchanted_book>.withTag(' + tag(recipe['enchantment'], recipe['level']) + ')'
        else:
            result = ingredient(recipe['output'])
            required.add(recipe['output'])
            lines.append('recipes.remove(' + result + ');')
            if recipe['count'] != 1:
                result += ' * ' + str(recipe['count'])
        lines += ['recipes.addShaped("dead_earth_progression_%s", %s, [%s]);' % (name, result, ', '.join(grid)), '']
    if len(data['books']) != 14:
        raise ValueError('Expected EfficiencyIV-X/FortuneIII-V/UnbreakingIII-V/SilkI books')
    for drop in sieve['drops']:
        if not ITEM.fullmatch(drop['input']) or not ITEM.fullmatch(drop['output']) or not 0 < drop['chance'] <= 1 or drop['mesh'] not in (1, 2, 3, 4):
            raise ValueError('Invalid native sieve reward')
        required.update((drop['input'], drop['output']))
    positives = dict(emc['allowlist'])
    positives.update(legacy_materials.raw_values(root))
    sieve_report = legacy_sieve_pricing.report(root, positives)
    sieve_prices = {token: row['emc'] for token, row in sieve_report['materials'].items()}
    positives.update(sieve_prices)
    zone_compressed = compressed_raw_values(root, positives)
    if type(emc.get('sieveInputEmc')) is not bool:
        raise ValueError('Explicit sieve input EMC policy is required')
    blocked = set() if emc['sieveInputEmc'] else sieve_input_keys(root)
    for item in blocked: positives.pop(item, None)
    required.update(item.replace('|', ':') for item in blocked)
    sieve_report['sieveInputEmc'] = emc['sieveInputEmc']
    compressed = compressed_raw_values(root, positives)
    positives.update(compressed)
    for item, value in positives.items():
        if not re.fullmatch(r'[a-z0-9_]+:[a-z0-9_./]+\|[0-9]+', item) or type(value) is not int or value <= 0:
            raise ValueError('Invalid explicit raw EMC')
        if item not in compressed and any(word in item for word in ('plate_', 'circuit', 'steel', 'fuel', 'srparasites:', 'dead_earth:')):
            raise ValueError('Technology/trophy/fuel leaked into raw EMC allowlist')
        required.add(item.replace('|', ':'))
    zeros = set(emc['explicitZero']) | blocked
    if set(positives) & zeros:
        raise ValueError('Conflicting EMC policy')
    entries = [{'item': item, 'emc': value} for item, value in sorted(positives.items())]
    entries += [{'item': item, 'emc': 0} for item in sorted(zeros)]
    mapping = ['# Only explicit raw values. No crafting, ore-dictionary, API, fluid or smelting propagation.',
               'general {', '    B:pregenerate=false', '    B:dumpEverythingToFile=false', '}', '', 'enabledmappers {']
    mapping += ['    B:' + mapper + '=' + ('true' if mapper == 'CustomEMCMapper' else 'false') for mapper in MAPPERS]
    mapping += ['}', '']
    # Forge Configuration canonicalizes category names to lower case, property names remain case sensitive.
    native_sieve = ['# Keep native defaults plus our registered provider on every reload.', 'exnihilocreatio {',
                    '    misc {', '        B:enableJSONLoading=false', '    }',
                    '    sieve {', '        B:flattenSieveRecipes=false', '    }', '}', '']
    result = {'legacy/pack/scripts/dead_earth_progression.zs': ('\n'.join(lines)).encode(),
              'legacy/pack/config/ProjectE/mapping.cfg': ('\n'.join(mapping)).encode(),
              'legacy/pack/config/exnihilocreatio/ExNihiloCreatio.cfg': ('\n'.join(native_sieve)).encode()}
    result['legacy/progression/sieve-pricing-report.json'] = (json.dumps(sieve_report, indent=2) + '\n').encode()
    for path, value in {'legacy/pack/config/ProjectE/custom_emc.json': {'__comment': emc['policy'], 'entries': entries},
                        'legacy/pack/config/dead-earth/progression.json': {'schema': 1, 'requiredItems': sorted(required), 'sieve': sieve['drops'], 'rawEmc': positives}}.items():
        result[path] = (json.dumps(value, indent=2) + '\n').encode()
    heavy = json.loads((root / 'legacy/sieving/heavy-entries.json').read_text(encoding='utf-8'))
    result['legacy/pack/config/ExCompressum/HeavySieve.json'] = (json.dumps({'options': {'loss for default generated rewards (out of 9)': 0}, 'defaults': {}, 'custom': {'entries': heavy}}, indent=2) + '\n').encode()
    result.update(legacy_materials.products(root))
    for group in legacy_materials.load(root)[1]: required.add(group['canonical'])
    # Canonical entries and legacy same-form aliases share zone prices.
    coordinator = json.loads((root / 'legacy/pack/config/dead-earth/coordinator.json').read_text(encoding='utf-8'))
    coordinator['resourcePrices'].update(legacy_materials.zone_values(root))
    for item, value in sieve_prices.items():
        coordinator['resourcePrices'][item.replace('|', ':')] = value
        if item.endswith('|0'):
            coordinator['resourcePrices'][item[:-2]] = value
    for item, value in zone_compressed.items(): coordinator['resourcePrices'][item.replace('|', ':')] = value
    result['legacy/pack/config/dead-earth/coordinator.json'] = (json.dumps(coordinator, indent=2) + '\n').encode()
    generated_progression = json.loads(result['legacy/pack/config/dead-earth/progression.json'])
    generated_progression['requiredItems'] = sorted(required)
    result['legacy/pack/config/dead-earth/progression.json'] = (json.dumps(generated_progression, indent=2) + '\n').encode()
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    for name, data in products().items():
        path = ROOT / name
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        elif path.read_bytes() != data:
            raise SystemExit('Stale progression artifact: ' + name)
    print('Generated full progression artifacts.' if args.write else 'Progression sources match packaged artifacts.')


if __name__ == '__main__':
    main()
